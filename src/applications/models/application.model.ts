import {
  Column, CreatedAt, DataType, HasMany, Model, PrimaryKey, Table, UpdatedAt,
} from 'sequelize-typescript';
import { APPLICATION_STATUSES, ApplicationStatus } from '../application-status';
import { ApplicationStatusHistory } from './application-status-history.model';
import { LoanAgreement } from '../../agreements/models/loan-agreement.model';

const str = (len: number, field: string, allowNull = false) => ({ type: DataType.STRING(len), field, allowNull });

/**
 * Loan application. NUMERIC columns come back from pg as strings; use the
 * mappers in application.mapper.ts to build API responses — never return a
 * model instance directly (it contains ciphertext columns).
 */
@Table({ tableName: 'applications', underscored: true })
export class Application extends Model {
  /** 6-char alphanumeric id (e.g. 56T65T), generated by ApplicationsService. */
  @PrimaryKey @Column(DataType.CHAR(6))
  declare id: string;

  @Column({ type: DataType.UUID, allowNull: false, defaultValue: DataType.UUIDV4 })
  declare uuid: string;

  @Column({ type: DataType.STRING(20), allowNull: false })
  declare reference: string;

  @Column({ type: DataType.ENUM(...APPLICATION_STATUSES), allowNull: false, defaultValue: ApplicationStatus.RECEIVED })
  declare status: ApplicationStatus;

  // loan
  @Column({ type: DataType.DECIMAL(12, 2), field: 'loan_amount', allowNull: false }) declare loanAmount: string;
  @Column(str(40, 'loan_purpose')) declare loanPurpose: string;
  @Column(str(200, 'loan_other_purpose', true)) declare loanOtherPurpose: string | null;

  // personal
  @Column(str(100, 'first_name')) declare firstName: string;
  @Column(str(100, 'last_name')) declare lastName: string;
  @Column(str(254, 'email')) declare email: string;
  @Column(str(10, 'phone')) declare phone: string;
  @Column({ type: DataType.DATEONLY, field: 'date_of_birth', allowNull: false }) declare dateOfBirth: string;
  @Column({ type: DataType.TEXT, field: 'ssn_encrypted', allowNull: false }) declare ssnEncrypted: string;
  @Column({ type: DataType.CHAR(4), field: 'ssn_last4', allowNull: false }) declare ssnLast4: string;
  @Column({ type: DataType.TEXT, field: 'dl_number_encrypted', allowNull: false }) declare dlNumberEncrypted: string;
  @Column({ type: DataType.CHAR(2), field: 'dl_state', allowNull: false }) declare dlState: string;
  @Column(str(200, 'street_address')) declare streetAddress: string;
  @Column(str(200, 'address_line2', true)) declare addressLine2: string | null;
  @Column(str(100, 'city')) declare city: string;
  @Column({ type: DataType.CHAR(2), allowNull: false }) declare state: string;
  @Column({ type: DataType.CHAR(5), allowNull: false }) declare zip: string;
  @Column({ type: DataType.DECIMAL(4, 1), field: 'years_at_address', allowNull: false }) declare yearsAtAddress: string;
  @Column(str(30, 'housing_status')) declare housingStatus: string;
  @Column({ type: DataType.DECIMAL(12, 2), field: 'monthly_housing_cost', allowNull: false }) declare monthlyHousingCost: string;

  // employment
  @Column(str(30, 'employment_status')) declare employmentStatus: string;
  @Column(str(200, 'employer_name', true)) declare employerName: string | null;
  @Column(str(120, 'job_title', true)) declare jobTitle: string | null;
  @Column({ type: DataType.INTEGER, field: 'employment_length_mo' }) declare employmentLengthMo: number | null;
  @Column(str(10, 'employer_phone', true)) declare employerPhone: string | null;
  @Column(str(30, 'pay_frequency')) declare payFrequency: string;
  @Column({ type: DataType.DATEONLY, field: 'next_pay_date', allowNull: false }) declare nextPayDate: string;
  @Column({ type: DataType.DECIMAL(12, 2), field: 'net_monthly_income', allowNull: false }) declare netMonthlyIncome: string;
  @Column(str(30, 'income_source')) declare incomeSource: string;

  // banking
  @Column(str(200, 'bank_name')) declare bankName: string;
  @Column(str(20, 'account_type')) declare accountType: string;
  @Column({ type: DataType.TEXT, field: 'routing_number_encrypted', allowNull: false }) declare routingNumberEncrypted: string;
  @Column({ type: DataType.TEXT, field: 'account_number_encrypted', allowNull: false }) declare accountNumberEncrypted: string;
  @Column({ type: DataType.CHAR(4), field: 'account_last4', allowNull: false }) declare accountLast4: string;
  @Column({ type: DataType.TEXT, field: 'bank_username_encrypted', allowNull: false }) declare bankUsernameEncrypted: string;
  @Column(str(40, 'account_age')) declare accountAge: string;
  @Column(str(40, 'current_balance_band')) declare currentBalanceBand: string;
  @Column({ type: DataType.BOOLEAN, field: 'direct_deposit', allowNull: false }) declare directDeposit: boolean;

  // consent
  @Column({ type: DataType.BOOLEAN, field: 'consent_esign', allowNull: false }) declare consentEsign: boolean;
  @Column({ type: DataType.BOOLEAN, field: 'consent_privacy', allowNull: false }) declare consentPrivacy: boolean;
  @Column({ type: DataType.BOOLEAN, field: 'consent_credit_pull', allowNull: false }) declare consentCreditPull: boolean;
  @Column({ type: DataType.BOOLEAN, field: 'consent_tcpa', allowNull: false }) declare consentTcpa: boolean;
  @Column(str(64, 'consent_ip', true)) declare consentIp: string | null;
  @Column(str(255, 'consent_user_agent', true)) declare consentUserAgent: string | null;

  // duplicate protection
  @Column(str(100, 'idempotency_key', true)) declare idempotencyKey: string | null;
  @Column({ type: DataType.CHAR(64), field: 'submission_fingerprint', allowNull: false }) declare submissionFingerprint: string;

  @Column({ type: DataType.DATE, field: 'submitted_at', allowNull: false, defaultValue: DataType.NOW }) declare submittedAt: Date;
  @Column({ type: DataType.DATE, field: 'status_changed_at', allowNull: false, defaultValue: DataType.NOW }) declare statusChangedAt: Date;
  @CreatedAt @Column({ field: 'created_at' }) declare createdAt: Date;
  @UpdatedAt @Column({ field: 'updated_at' }) declare updatedAt: Date;

  @HasMany(() => ApplicationStatusHistory) declare statusHistory?: ApplicationStatusHistory[];
  @HasMany(() => LoanAgreement) declare agreements?: LoanAgreement[];
}
